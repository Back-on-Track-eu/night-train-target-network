# The provenance column is UI-facing wording, derived from the qualification
# layer and the step 6 reason criterion. Editing a label here is enough — the
# detailed per-stop reasons stay in data/step6_manual_additions.csv and the
# step 6 notebook, which remain the record of the selection decisions.
PROVENANCE_LABELS = {
    "night_train_stop": "existing night train stop",
    "fua": "urban area currently without night train service",
    "tourism": "tourism region currently without night train service",
    "ferry": "ferry port currently without night train service",
    "border": "border / interchange station",
    "network": "network coherence addition",
}
PROVENANCE_FALLBACK = "manual addition"


def provenance_label(source: str, reason: str) -> str:
    if source == "step5":
        return PROVENANCE_LABELS["night_train_stop"]
    criterion = reason.partition(":")[0].split(" ")[0].strip()
    return PROVENANCE_LABELS.get(criterion, PROVENANCE_FALLBACK)


