"""
Step 10 — export the qualified catalog in the shape db/dev/seed.py consumes.

Unions the current step 5 output (Tier 1: current night train stops) with the
step 6 manual additions and writes a CSV matching seed.py's
_ONTD_SEED_CSV_COLUMNS contract exactly. Keyed on OSM id, so a stop qualifying
both ways is written once and a step 5 re-run flows straight into the catalog
without touching the manual selection.

Which layer a stop came from is written alongside, to
stop_seed_provenance.csv: the catalog itself has to match seed.py's column
contract exactly, so the provenance can't ride in it. Without that sidecar
nothing on disk distinguishes a stop a night train serves today from one added
by hand.

country
    Taken from the ONTD export via the step 4 join where one exists, since ONTD
    is curated national data; otherwise the source layer's own value. Steps 5
    and 6 already apply the same preference, so this is a safety net rather
    than the place the correction happens — step 6 reports what it changed.

stop_timezone
    Derived from the country as an IANA name. The legacy step 6 file carried a
    bare UTC offset instead, which cannot express DST and was wrong for Ireland
    (marked +1); the schema and the rest of the catalog use IANA names.

The catalog is a single file carrying everything downstream needs: the
seven seed contract columns first (seed.py validates them as a header
prefix and ignores the rest until the schema migration), then a
human-readable provenance category, then the step 7 name/city/language
columns and the step 8 gauges. Step 7's enrichment is therefore a required
input; step 8's gauges are joined when present and warned about when not
(Overpass-dependent, resumable — the catalog should not block on it).

Two invariants guard the union against duplicate stations:
- no two catalog rows may share an ONTD id (same station through two OSM
  objects) — hard error;
- rows within 200 m of each other are reported for review (step 6's guards
  should have caught them; this is the belt to those braces).

stop_charge_eur comes from charges/data/station_charges.csv, generated by the
charge calibration notebooks in charges/, and is joined together with its
provenance: the VAT rate and the gross figure, what the charge is per, the
year it was published for, the country's own tariff class, and the source
document. A figure in a published catalog that cannot say where it came from
is not much better than no figure. A stop absent from that file is
written empty and seed.py inserts NULL, which resolves through the
country/global default (currently 11.28 EUR).
Empty is deliberate: a placeholder number would override that fallback and make
"which stops still need real charge data?" unanswerable, whereas NULL keeps the
question a one-line query.

Run from this directory:

    uv run python step10_export_seed_stops.py
"""

